// Tongue on firmware builds the eye/face enhancement does not know.
//
// The enhancement hooks PICO's tracking plugin at fixed offsets and therefore only runs on the
// firmware it was verified against. The tongue needs just one thing from the plugin: the mouth
// image handed to FaceTrackor. This finds that function by its code instead of its address: the
// first instructions of the verified build with every relocatable field masked (branch targets,
// page addresses, struct and stack offsets), compared at every instruction boundary of the
// plugin's code, tolerating a few differing instructions. Exactly one place may match; otherwise
// nothing is hooked and the service stays stock.
//
// The match is only observed (instruction interceptor, the function itself runs untouched), and
// tongue_shadow() reads the image header through process_vm_readv and rejects anything that is
// not an 8-bit single-channel image, so a wrong match cannot crash the service.
#include <cstddef>
#include <cstdint>
#include <cstring>

