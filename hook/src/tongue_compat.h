// Returns the address of the single match in [text, text + size), or 0. `mismatches` gets the
// number of differing instructions of the best candidate, `candidates` how many places matched.
static uintptr_t find_trackor(uintptr_t text, size_t size, unsigned& mismatches, unsigned& candidates) {
    mismatches = kTrackorWords; candidates = 0;
    if (size < kTrackorWords * 4) return 0;
    uintptr_t found = 0;
    const size_t last = (size - kTrackorWords * 4) & ~size_t(3);
    for (size_t off = 0; off <= last; off += 4) {
        const unsigned char* p = reinterpret_cast<const unsigned char*>(text + off);
        unsigned miss = 0;
        for (unsigned k = 0; k < kTrackorWords && miss <= kTrackorTolerance; k++) {
            uint32_t w; memcpy(&w, p + 4 * k, 4);
            miss += (w & kTrackorSig[k][1]) != kTrackorSig[k][0];
        }
        if (miss > kTrackorTolerance) continue;
        candidates++;
        if (miss < mismatches) { mismatches = miss; found = text + off; }
    }
    return candidates == 1 ? found : 0;
}
