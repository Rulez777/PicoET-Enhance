"""Export shadow-final.pt to a C header for the headset payload (BatchNorm folded into convs)
plus reference data for the on-device numeric check:
  device/frames200.u8      168 frames, 200x200 uint8, dataset-index order
  device/ref-logits.f32    PyTorch CPU float32 56x56 logits for the same frames"""
from pathlib import Path
import hashlib, json, sys
import numpy as np
import torch
from torch import nn
from torchvision.ops.misc import SqueezeExcitation
from PIL import Image

here = Path(__file__).resolve().parent
sys.path.insert(0, str(here))
from shadow_model import Segment, to_input, downsample400, CALIBRATION  # noqa: E402
MODEL = sys.argv[1] if len(sys.argv) > 1 else 'shadow-final.pt'

model = Segment(pretrained=False)
model.load_state_dict(torch.load(here / MODEL, map_location='cpu'))
model.eval()

weights = []
ops = []          # (type, in, out, k, stride, groups, act, woff, boff, sq, w2off, b2off)
CONV, SE, RES_SAVE, RES_ADD, TAP = 0, 1, 2, 3, 4
NONE, RELU, HSWISH = 0, 1, 2


def push(a):
    off = sum(len(w) for w in weights)
    weights.append(np.asarray(a, np.float32).ravel())
    return off


def conv_bn_act(seq):
    conv, bn = seq[0], seq[1]
    act = NONE
    if len(seq) > 2:
        act = RELU if isinstance(seq[2], nn.ReLU) else HSWISH
        assert isinstance(seq[2], (nn.ReLU, nn.Hardswish))
    scale = (bn.weight / torch.sqrt(bn.running_var + bn.eps)).detach()
    w = conv.weight.detach() * scale[:, None, None, None]
    b = (bn.bias - bn.running_mean * scale).detach()
    ops.append((CONV, conv.in_channels, conv.out_channels, conv.kernel_size[0], conv.stride[0],
                conv.groups, act, push(w), push(b), 0, 0, 0))


for i, block in enumerate(model.encoder):
    if i == 0:
        conv_bn_act(block)
    else:
        if block.use_res_connect:
            ops.append((RES_SAVE,) + (0,) * 11)
        for layer in block.block:
            if isinstance(layer, SqueezeExcitation):
                ops.append((SE, layer.fc1.in_channels, layer.fc1.in_channels, 1, 1, 1, NONE,
                            push(layer.fc1.weight.detach()), push(layer.fc1.bias.detach()), layer.fc1.out_channels,
                            push(layer.fc2.weight.detach()), push(layer.fc2.bias.detach())))
            else:
                conv_bn_act(layer)
        if block.use_res_connect:
            ops.append((RES_ADD,) + (0,) * 11)
    if i in (1, 3, 8):
        ops.append((TAP, i) + (0,) * 10)

head = []
for layer in model.head:
    if isinstance(layer, nn.Conv2d):
        head.append([layer.in_channels, layer.out_channels, layer.kernel_size[0],
                     push(layer.weight.detach()), push(layer.bias.detach())])
assert [h[:3] for h in head] == [[89, 16, 1], [16, 16, 3], [16, 1, 1]]

flat = np.concatenate(weights)
sha = hashlib.sha256((here / MODEL).read_bytes()).hexdigest()
lines = ['#pragma once', f'// Generated by export_headset_model.py from {MODEL} sha256 {sha}.',
         '// MobileNetV3-small blocks 0..8 (BN folded) + mask head. Do not edit by hand.',
         'namespace tongue_seg_weights {',
         'struct Op { int type, in, out, k, stride, groups, act, woff, boff, sq, w2off, b2off; };',
         f'static const Op ops[{len(ops)}] = {{']
lines += ['  {' + ','.join(str(int(v)) for v in op) + '},' for op in ops]
lines.append('};')
lines.append('static const float angle_left = %.4ff, angle_center = %.4ff, angle_right = %.4ff;' % CALIBRATION[MODEL])
lines.append('static const int head[3][5] = {' + ','.join('{' + ','.join(map(str, h)) + '}' for h in head) + '};')
lines.append(f'static const float w[{len(flat)}] = {{')
for k in range(0, len(flat), 8):
    lines.append('  ' + ','.join(f'{v:.9e}f' for v in flat[k:k + 8]) + ',')
lines.append('};')
lines.append('}')
out = here.parent / 'PicoET-Shadow' / 'hook' / 'src' / 'tongue_seg_weights.h'
out.write_text('\n'.join(lines) + '\n')
print('ops', len(ops), 'floats', len(flat), '->', out)

# reference data
dev = here / 'device'
rows = json.loads((here.parent / 'dataset-index.json').read_text())
frames = np.stack([downsample400(np.asarray(Image.open(here.parent.parent / r['path'].replace('\\', '/')))) for r in rows])
frames.tofile(dev / 'frames200.u8')
with torch.inference_mode():
    logits = model(to_input(torch.from_numpy(frames))).numpy()[:, 0].astype(np.float32)
logits.tofile(dev / 'ref-logits.f32')
print('reference', frames.shape, logits.shape)
